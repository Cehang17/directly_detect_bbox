/**
 * AccessibilityEnricher - Generates PDF/UA and WCAG Table Accessibility Metadata
 * Computes roles (th/td), scopes (col/row/colgroup/rowgroup), and header associations.
 */

function enrichTable(table) {
  if (!table || typeof table !== 'object') return table;
  const cells = Array.isArray(table.cells) ? table.cells : [];
  if (cells.length === 0) return table;

  const isHeaderCell = c => Boolean(c.isHeader ?? c.is_header ?? c.is_head ?? (c.row === 0));
  const isHeaderRow = r => cells.filter(c => c.row === r).every(isHeaderCell);
  const isHeaderCol = c0 => cells.filter(c => c.col === c0).every(isHeaderCell);

  const newCellsA11y = {};

  cells.forEach((cell, idx) => {
    const cellId = cell.id || `c_${cell.row ?? 0}_${cell.col ?? idx}`;
    const isHead = isHeaderCell(cell);
    const role = isHead ? "th" : "td";
    let scope = null;
    let headers = [];

    if (isHead) {
      const spansMultiCol = ((cell.colSpan ?? cell.colspan ?? cell.col_span) || 1) > 1;
      const spansMultiRow = ((cell.rowSpan ?? cell.rowspan ?? cell.row_span) || 1) > 1;
      if (spansMultiCol) scope = "colgroup";
      else if (spansMultiRow) scope = "rowgroup";
      else scope = isHeaderRow(cell.row) ? "col" : (isHeaderCol(cell.col) ? "row" : "col");
    } else {
      const relatedHeaders = cells.filter(h => {
        if (!isHeaderCell(h)) return false;
        const hRow = h.row ?? 0;
        const hCol = h.col ?? 0;
        const cRow = cell.row ?? 0;
        const cCol = cell.col ?? 0;
        const hRowSpan = (h.rowSpan ?? h.rowspan ?? h.row_span ?? 1);
        const hColSpan = (h.colSpan ?? h.colspan ?? h.col_span ?? 1);

        const spansRow = cRow >= hRow && cRow < hRow + hRowSpan;
        const spansCol = cCol >= hCol && cCol < hCol + hColSpan;
        return (spansCol && hRow < cRow) || (spansRow && hCol < cCol);
      });
      if (relatedHeaders.length >= 1) {
        headers = relatedHeaders.map(h => h.id || `c_${h.row}_${h.col}`);
      }
    }

    newCellsA11y[cellId] = { role, scope, headers, autoGenerated: true };
  });

  // Elle düzeltilmiş değerleri koru
  const existing = table.accessibility?.cells || {};
  Object.keys(existing).forEach(id => {
    if (existing[id] && existing[id].autoGenerated === false) {
      newCellsA11y[id] = existing[id];
    }
  });

  return {
    ...table,
    accessibility: {
      caption: table.accessibility?.caption ?? null,
      summary: table.accessibility?.summary ?? null,
      cells: newCellsA11y,
    },
  };
}

function enrichDocument(documentJson) {
  if (!documentJson || typeof documentJson !== 'object') return documentJson;

  // If documentJson has tables array
  if (Array.isArray(documentJson.tables)) {
    return { ...documentJson, tables: documentJson.tables.map(enrichTable) };
  }

  // If documentJson itself is a table or has cells
  if (Array.isArray(documentJson.cells)) {
    return enrichTable(documentJson);
  }

  return documentJson;
}

if (typeof window !== "undefined") {
  window.AccessibilityEnricher = { enrichTable, enrichDocument };
  window.enrichTable = enrichTable;
  window.enrichDocument = enrichDocument;
}

if (typeof module !== "undefined" && module.exports) {
  module.exports = { enrichTable, enrichDocument };
}
